import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const extractedPath = path.join(__dirname, 'admin-ui-extracted.json');
const rows = JSON.parse(fs.readFileSync(extractedPath, 'utf8'));

function slugifyEn(en) {
  const s = String(en || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '')
    .slice(0, 56);
  return s || 'x';
}

const used = new Map();
const keys = [];
for (const row of rows) {
  let base = slugifyEn(row.en);
  let k = base;
  let n = 1;
  while (used.has(k)) {
    n += 1;
    k = `${base}_${n}`;
  }
  used.set(k, true);
  keys.push({ k, vi: row.vi, es: row.es, en: row.en });
}

keys.sort((a, b) => a.k.localeCompare(b.k));

function esc(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function emitObj(rows2, field, innerIndent) {
  const pad = ' '.repeat(innerIndent);
  const lines = rows2.map((r) => `${pad}${r.k}: '${esc(r[field])}',`);
  return lines.join('\n');
}

const viBlock = emitObj(keys, 'vi', 6);
const esBlock = emitObj(keys, 'es', 4);
const enBlock = emitObj(keys, 'en', 4);

const out = `
// --- adminUi namespace (generated by scripts/build-admin-ui-namespace.mjs) ---
    adminUi: {
${viBlock}
    },
`;

const outEs = `
  adminUi: {
${esBlock}
  },
`;

const outEn = `
  adminUi: {
${enBlock}
  },
`;

fs.writeFileSync(path.join(__dirname, 'admin-ui-vi-snippet.txt'), out);
fs.writeFileSync(path.join(__dirname, 'admin-ui-es-snippet.txt'), outEs);
fs.writeFileSync(path.join(__dirname, 'admin-ui-en-snippet.txt'), outEn);

const mapLines = keys.map((r) => `  '${esc(r.vi)}': 'adminUi.${r.k}',`);
fs.writeFileSync(
  path.join(__dirname, 'admin-ui-vi-to-key.txt'),
  `export const adminViToKey = {\n${mapLines.join('\n')}\n};\n`
);

console.error('adminUi keys:', keys.length);
console.error('Wrote snippets to scripts/admin-ui-*-snippet.txt and admin-ui-vi-to-key.txt');
